@Composable
fun AIAgentTestAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    /**
     * Off by default, on purpose. Dynamic colour re-tints the whole app from the wallpaper,
     * which in practice washed every screen into the wallpaper's grey and erased the brand --
     * the indigo/teal/amber roles the screens are designed around. The parameter stays so a
     * wallpaper-matched look is one flag away if it is ever wanted.
     */
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = AppShapes,
        content = content,
    )
}
